using UnityEngine;
using UnityEngine.UI;

namespace StarterAssets
{
    /// <summary>
    /// Displays circular cooldown buttons for each skill.
    /// Attach to a Canvas GameObject and assign references in Inspector.
    /// Each skill button shows a radial fill overlay + remaining time text.
    /// </summary>
    public class SkillCooldownUI : MonoBehaviour
    {
        [Header("Player Reference")]
        [Tooltip("Drag the Player (ThirdPersonController) here. If empty, auto-finds by tag 'Player'.")]
        public ThirdPersonController player;

        [Header("Ultimate Skill (R)")]
        [Tooltip("Cooldown overlay image (Image type=Filled, Fill Method=Radial360)")]
        public Image ultimateCooldownFill;
        [Tooltip("Text showing remaining seconds")]
        public Text ultimateCooldownText;
        [Tooltip("Optional: icon tint when skill is ready")]
        public Image ultimateIcon;

        [Header("E Skill (E)")]
        public Image eskillCooldownFill;
        public Text eskillCooldownText;
        public Image eskillIcon;

        [Header("Protect (Q)")]
        public Image protectCooldownFill;
        public Text protectCooldownText;
        public Image protectIcon;

        [Header("Roll (Space)")]
        public Image rollCooldownFill;
        public Text rollCooldownText;
        public Image rollIcon;

        [Header("Visual Settings")]
        [Tooltip("Color of the cooldown overlay")]
        public Color cooldownOverlayColor = new Color(0f, 0f, 0f, 0.6f);
        [Tooltip("Icon color when skill is ready")]
        public Color readyColor = Color.white;
        [Tooltip("Icon color when skill is on cooldown")]
        public Color cooldownColor = Color.white;
        [Tooltip("Hide cooldown text when skill is ready")]
        public bool hideTextWhenReady = true;

        private void Start()
        {
            if (player == null)
            {
                GameObject playerObj = GameObject.FindGameObjectWithTag("Player");
                if (playerObj != null)
                    player = playerObj.GetComponent<ThirdPersonController>();
            }

            if (player == null)
            {
                Debug.LogError("SkillCooldownUI: ThirdPersonController not found! Assign player in Inspector.");
                enabled = false;
                return;
            }

            // Initialize fill colors
            if (ultimateCooldownFill != null) ultimateCooldownFill.color = cooldownOverlayColor;
            if (eskillCooldownFill != null) eskillCooldownFill.color = cooldownOverlayColor;
            if (protectCooldownFill != null) protectCooldownFill.color = cooldownOverlayColor;
            if (rollCooldownFill != null) rollCooldownFill.color = cooldownOverlayColor;

            // Force icons to white so they display original sprite colors
            if (ultimateIcon != null) ultimateIcon.color = Color.white;
            if (eskillIcon != null) eskillIcon.color = Color.white;
            if (protectIcon != null) protectIcon.color = Color.white;
            if (rollIcon != null) rollIcon.color = Color.white;

            // Fix Border overlays that wash out icon colors
            // Border sits on top of icon in the hierarchy, making icons appear faded
            FixBorderOverlay(ultimateIcon);
            FixBorderOverlay(eskillIcon);
            FixBorderOverlay(protectIcon);
            FixBorderOverlay(rollIcon);
        }

        /// <summary>
        /// Moves Border object behind the icon so it doesn't wash out the icon color.
        /// Border is a sibling of IconMask in the button hierarchy.
        /// </summary>
        private void FixBorderOverlay(Image icon)
        {
            if (icon == null) return;

            // Icon is inside IconMask, which is inside the button root
            Transform maskTransform = icon.transform.parent;
            if (maskTransform == null) return;
            Transform buttonRoot = maskTransform.parent;
            if (buttonRoot == null) return;

            Transform border = buttonRoot.Find("Border");
            if (border != null)
            {
                // Move Border to index 0 (behind everything else)
                border.SetAsFirstSibling();
            }
        }

        private void Update()
        {
            if (player == null) return;

            UpdateSkillButton(
                player.IsUltimateReady(),
                player.GetUltimateCooldownProgress(),
                player.GetUltimateRemainingCooldown(),
                ultimateCooldownFill,
                ultimateCooldownText,
                ultimateIcon
            );

            UpdateSkillButton(
                player.IsESkillReady(),
                player.GetESkillCooldownProgress(),
                player.GetESkillRemainingCooldown(),
                eskillCooldownFill,
                eskillCooldownText,
                eskillIcon
            );

            UpdateSkillButton(
                player.IsProtectReady(),
                player.GetProtectCooldownProgress(),
                player.GetProtectRemainingCooldown(),
                protectCooldownFill,
                protectCooldownText,
                protectIcon
            );

            UpdateSkillButton(
                player.IsRollReady(),
                player.GetRollCooldownProgress(),
                player.GetRollRemainingCooldown(),
                rollCooldownFill,
                rollCooldownText,
                rollIcon
            );
        }

        private void UpdateSkillButton(bool isReady, float progress, float remaining,
            Image fillImage, Text cooldownText, Image icon)
        {
            // Update fill overlay (1 = full cover = on cooldown, 0 = no cover = ready)
            if (fillImage != null)
            {
                fillImage.fillAmount = isReady ? 0f : 1f - progress;
            }

            // Update countdown text
            if (cooldownText != null)
            {
                if (isReady)
                {
                    if (hideTextWhenReady)
                        cooldownText.text = "";
                    else
                        cooldownText.text = "OK";
                }
                else
                {
                    cooldownText.text = Mathf.CeilToInt(remaining).ToString();
                }
            }

            // Icon always keeps original sprite color (white tint = no modification)
            // Cooldown state is shown via the fill overlay only
        }
    }
}



























































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































