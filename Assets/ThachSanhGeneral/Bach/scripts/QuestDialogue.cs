/// </summary>
public class QuestDialogue : MonoBehaviour
{
    // ?? Key l?u tr?ng thái boss (PlayerPrefs) ?????????????????????????????
    public const string KEY_CHAN_TINH_DEAD  = "BossChanTinhDead";
