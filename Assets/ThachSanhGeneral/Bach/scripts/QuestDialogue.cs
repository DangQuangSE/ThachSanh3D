/// <summary>
/// H? th?ng h?i tho?i nh?n nhi?m v? ?ánh boss.
/// G?n script này lên NPC/GameObject t??ng tác.
/// Dùng PlayerPrefs ?? l?u ti?n trình gi?a các scene.
/// H? tr? c? Legacy Text và TextMeshPro.
